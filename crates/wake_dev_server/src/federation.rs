//! Immutable development artifacts for Wake-native federation remotes.
//!
//! The retained bundler session remains owned by `wake_dev_server::watch_and_rebuild`. This module
//! is deliberately a pure output coordinator: it binds one successful [`BuildOutput`] to a
//! versioned manifest, a complete in-memory HTTP route set, and (after the first build) one
//! semantic [`DevUpdate`]. A failed assembly never replaces the last good snapshot.

