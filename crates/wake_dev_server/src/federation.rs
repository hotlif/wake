    #[test]
    fn declaration_only_change_emits_types_only_without_changed_exposes() {
        let kind = Arc::new(Mutex::new("string".to_owned()));
        let mut options = options(ExposeMode::Generic);
        options.type_emitter = Some(type_emitter(Arc::clone(&kind)));
        let output = output("globalThis.Button = 1;", "button.ts");
        let (first, _) = FederationSnapshot::assemble(
            &options,
            &output,
            test_generation_file_system(),
            "/",
            "ws://localhost:5173/__wake_federation_updates?remote=catalog",
            None,
        )
        .unwrap();
        *kind.lock().unwrap() = "number".to_owned();
        let (second, update) = FederationSnapshot::assemble(
            &options,
            &output,
            test_generation_file_system(),
            "/",
            "ws://localhost:5173/__wake_federation_updates?remote=catalog",
            Some(&first),
        )
        .unwrap();
        let update = update.unwrap();
        assert_eq!(second.generation(), 2);
        assert_eq!(update.action, DevUpdateAction::TypesOnly);
        assert!(update.changed_exposes.is_empty());
        assert!(update.types_hash.is_some());
        assert!(
            second
                .route(&format!(
                    "@wake/federation/builds/{}/types.json",
                    second.manifest.build_id
                ))
                .is_some()
        );

        let oldest_lazy_path = format!(
            "@wake/federation/builds/{}/button.333.js",
            first.manifest.build_id
        );
        let oldest_lazy_bytes = first.route(&oldest_lazy_path).unwrap().bytes.clone();
        let mut retained = FederationSnapshotState::default();
        let oldest_lease = BTreeSet::from([first.manifest.build_id.clone()]);
        retained.install(first);
        retained
            .replace_leases(&BTreeSet::new(), &oldest_lease)
            .unwrap();
        retained.install(second.clone());
        *kind.lock().unwrap() = "boolean".to_owned();
        let (third, update) = FederationSnapshot::assemble(
            &options,
            &output,
            test_generation_file_system(),
            "/",
            "ws://localhost:5173/__wake_federation_updates?remote=catalog",
            Some(&second),
        )
        .unwrap();
        assert_eq!(update.unwrap().action, DevUpdateAction::TypesOnly);
        assert_eq!(third.generation(), 3);
        retained.install(third.clone());
        let mut latest = third;
        for generation in 4..=32 {
            *kind.lock().unwrap() = format!("\"type-{generation}\"");
            let (next, update) = FederationSnapshot::assemble(
                &options,
                &output,
                test_generation_file_system(),
                "/",
                "ws://localhost:5173/__wake_federation_updates?remote=catalog",
                Some(&latest),
            )
            .unwrap();
            assert_eq!(update.unwrap().action, DevUpdateAction::TypesOnly);
            assert_eq!(next.generation(), generation);
            retained.install(next.clone());
            latest = next;
        }
        assert_eq!(
            retained_route(&retained, &oldest_lazy_path).bytes,
            oldest_lazy_bytes,
            "a leased old runtime must retain lazy chunks across many types-only generations"
        );
        let current_manifest: Manifest =
            serde_json::from_slice(&retained_route(&retained, MANIFEST_PATH).bytes).unwrap();
        assert_eq!(current_manifest.build_id, latest.manifest.build_id);
        retained.release_leases(&oldest_lease);
        assert!(matches!(
            retained.route(&oldest_lazy_path),
            FederationRouteLookup::Gone { .. }
        ));
    }

