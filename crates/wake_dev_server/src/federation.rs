/// Number of recently retired generations retained without browser evidence. This covers the
/// manifest-to-entry race while keeping an idle development remote bounded.
pub(crate) const FEDERATION_SNAPSHOT_GRACE_GENERATIONS: u64 = 2;

#[derive(Debug, Clone)]
struct RetiredFederationRoutes {
    generation: u64,
    routes: BTreeMap<String, FederationRoute>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct FederationSnapshotCursor {
    pub remote: ContainerName,
    pub current_build_id: BuildId,
    pub generation: u64,
}

#[derive(Debug, Clone)]
pub(crate) enum FederationRouteLookup {
    Found(FederationRoute),
    Gone {
        cursor: FederationSnapshotCursor,
        expired_build_id: BuildId,
    },
    /// The request uses Wake's reserved Federation namespace, but no published artifact owns it.
    Missing,
    /// The request is outside Wake's reserved Federation namespace and may continue through the
    /// ordinary bundle, public-file, and SPA routing layers.
    NotFederation,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum FederationLeaseError {
    NoSnapshot,
    TooManyBuilds,
    UnknownBuild(BuildId),
}

/// Atomic route owner for one development remote. Stable routes resolve only from `current`.
/// Retired build routes survive while a browser WebSocket leases their build ID, plus a fixed
/// grace window for the manifest-to-entry race. No full snapshot is retained without evidence.
#[derive(Debug, Clone, Default)]
pub(crate) struct FederationSnapshotState {
    current: Option<FederationSnapshot>,
    history: BTreeMap<BuildId, RetiredFederationRoutes>,
    lease_counts: BTreeMap<BuildId, usize>,
}

impl FederationSnapshotState {
    pub fn current(&self) -> Option<&FederationSnapshot> {
        self.current.as_ref()
    }

    pub fn install(&mut self, snapshot: FederationSnapshot) {
        let next_build_id = snapshot.manifest.build_id.clone();
        if self
            .current
            .as_ref()
            .is_some_and(|current| current.manifest.build_id == next_build_id)
        {
            self.history.remove(&next_build_id);
            self.current = Some(snapshot);
            self.prune();
            return;
        }
        if let Some(current) = self.current.take() {
            let build_id = current.manifest.build_id.clone();
            let generation = current.generation();
            let route_prefix = format!("@wake/federation/builds/{build_id}/");
            let routes = current
                .routes
                .into_iter()
                .filter(|(path, _)| path.starts_with(&route_prefix))
                .collect();
            self.history
                .insert(build_id, RetiredFederationRoutes { generation, routes });
        }
        self.history.remove(&next_build_id);
        self.current = Some(snapshot);
        self.prune();
    }

    pub fn route(&self, path: &str) -> FederationRouteLookup {
        let Some(current) = self.current.as_ref() else {
            return if is_reserved_federation_route(path) {
                FederationRouteLookup::Missing
            } else {
                FederationRouteLookup::NotFederation
            };
        };
        let Some(build_id) = build_id_from_route(path) else {
            return current.route(path).cloned().map_or_else(
                || {
                    if is_reserved_federation_route(path) {
                        FederationRouteLookup::Missing
                    } else {
                        FederationRouteLookup::NotFederation
                    }
                },
                FederationRouteLookup::Found,
            );
        };
        if current.manifest.build_id == build_id {
            return current
                .route(path)
                .cloned()
                .map_or(FederationRouteLookup::Missing, FederationRouteLookup::Found);
        }
        if let Some(retired) = self.history.get(&build_id) {
            return retired
                .routes
                .get(path)
                .cloned()
                .map_or(FederationRouteLookup::Missing, FederationRouteLookup::Found);
        }
        FederationRouteLookup::Gone {
            cursor: self.cursor().expect("current snapshot was checked above"),
            expired_build_id: build_id,
        }
    }

    pub fn cursor(&self) -> Option<FederationSnapshotCursor> {
        let current = self.current.as_ref()?;
        Some(FederationSnapshotCursor {
            remote: current.manifest.name.clone(),
            current_build_id: current.manifest.build_id.clone(),
            generation: current.generation(),
        })
    }

    /// Atomically replaces the build leases owned by one WebSocket connection.
    /// Validation is completed before refcounts change, so invalid frames cannot grow history.
    pub fn replace_leases(
        &mut self,
        previous: &BTreeSet<BuildId>,
        requested: &BTreeSet<BuildId>,
    ) -> Result<FederationSnapshotCursor, FederationLeaseError> {
        let cursor = self.cursor().ok_or(FederationLeaseError::NoSnapshot)?;
        if requested.len() > FEDERATION_DEV_MAX_BUILD_LEASES {
            return Err(FederationLeaseError::TooManyBuilds);
        }
        if let Some(unknown) = requested.iter().find(|build_id| {
            **build_id != cursor.current_build_id && !self.history.contains_key(*build_id)
        }) {
            return Err(FederationLeaseError::UnknownBuild((*unknown).clone()));
        }

        for build_id in previous.difference(requested) {
            if let Some(count) = self.lease_counts.get_mut(build_id) {
                *count -= 1;
                if *count == 0 {
                    self.lease_counts.remove(build_id);
                }
            }
        }
        for build_id in requested.difference(previous) {
            *self.lease_counts.entry(build_id.clone()).or_default() += 1;
        }
        self.prune();
        Ok(cursor)
    }

    pub fn release_leases(&mut self, leases: &BTreeSet<BuildId>) {
        for build_id in leases {
            if let Some(count) = self.lease_counts.get_mut(build_id) {
                *count -= 1;
                if *count == 0 {
                    self.lease_counts.remove(build_id);
                }
            }
        }
        self.prune();
    }

    fn prune(&mut self) {
        let Some(current_generation) = self.current.as_ref().map(FederationSnapshot::generation)
        else {
            self.history.clear();
            self.lease_counts.clear();
            return;
        };
        self.history.retain(|build_id, retained| {
            self.lease_counts.get(build_id).copied().unwrap_or(0) > 0
                || current_generation.saturating_sub(retained.generation)
                    <= FEDERATION_SNAPSHOT_GRACE_GENERATIONS
        });
    }
}

fn is_reserved_federation_route(path: &str) -> bool {
    path == MANIFEST_PATH || path.starts_with("@wake/federation/")
}

fn build_id_from_route(path: &str) -> Option<BuildId> {
    let suffix = path.strip_prefix("@wake/federation/builds/")?;
    let (build_id, _) = suffix.split_once('/')?;
    let build_id = BuildId::from(build_id);
    build_id.is_valid().then_some(build_id)
}

impl FederationSnapshot {
    pub fn route(&self, path: &str) -> Option<&FederationRoute> {
        self.routes.get(path)
    }

    pub fn generation(&self) -> u64 {
        self.manifest
            .development
            .as_ref()
            .map_or(0, |development| development.generation)
    }

    pub fn assemble(
        options: &FederationBuildOptions,
        output: &BuildOutput,
        file_system: Arc<dyn FileSystem>,
        base_path: &str,
        updates_url: &str,
        previous: Option<&Self>,
    ) -> Result<(Self, Option<DevUpdate>), String> {
        if !options.enabled {
            return Err("federation snapshot requested for a disabled build".to_owned());
        }
        if options.container_name.is_empty() {
            return Err("federation container name is empty".to_owned());
        }
        let template = options
            .remote_entry_template
            .as_deref()
            .ok_or_else(|| "federation remote-entry template is missing".to_owned())?;
        if !template.contains(FEDERATION_BUILD_ID_PLACEHOLDER) {
            return Err(format!(
                "federation remote-entry template does not contain `{FEDERATION_BUILD_ID_PLACEHOLDER}`"
            ));
        }
        validate_expose_descriptors(options, output)?;

        let prepared_types = options
            .type_emitter
            .as_ref()
            .map(|emitter| emitter.prepare(file_system))
            .transpose()?;
        let types_identity = prepared_types
            .as_ref()
            .map(FederationTypeGeneration::identity_bytes)
            .map(|bytes| digest_bytes(bytes).0);

        let runtime_identity_bytes = runtime_identity_bytes(options, output)?;
        let runtime_identity = digest_bytes(&runtime_identity_bytes).0;
        let control_identity = digest_bytes(
            &serde_json::to_vec(&(
                options.container_name.as_str(),
                options.browser_target.as_str(),
                options.remote_entry_template.as_deref(),
                options.application_loader_export.as_deref(),
            ))
            .map_err(|error| error.to_string())?,
        )
        .0;
        let build_id = content_build_id(
            &runtime_identity_bytes,
            prepared_types
                .as_ref()
                .map(FederationTypeGeneration::identity_bytes),
        );
        let generation = previous.map_or(1, |snapshot| {
            if snapshot.manifest.build_id == build_id {
                snapshot.generation()
            } else {
                snapshot.generation().saturating_add(1)
            }
        });

        let remote_entry_abi = template.replace(FEDERATION_BUILD_ID_PLACEHOLDER, build_id.as_str());
        // The retained container entry is embedded exactly once in remoteEntry, matching the
        // production artifact. Its `import.meta.url` is therefore the SRI-checked, build-scoped
        // remoteEntry URL for which the broker installed the asset execution context.
        let remote_entry_source = format!("{}\n{remote_entry_abi}", output.bundle);
        let build_prefix = format!("@wake/federation/builds/{build_id}");
        let remote_entry_path = format!("{build_prefix}/{REMOTE_ENTRY_FILE}");
        let remote_entry_map_path = format!("{build_prefix}/{REMOTE_ENTRY_MAP_FILE}");
        let remote_entry_map = combined_remote_entry_map(
            output,
            &remote_entry_abi,
            &options.container_name,
            &build_id,
            &remote_entry_path,
        )?;
        let remote_entry = asset(
            AssetKind::JavaScript,
            relative_url(&remote_entry_path),
            remote_entry_source.as_bytes(),
            "text/javascript",
        );
        let remote_entry_source_map = asset(
            AssetKind::SourceMap,
            relative_url(&remote_entry_map_path),
            remote_entry_map.as_bytes(),
            "application/source-map+json",
        );

        let mut routes = output_routes(
            output,
            base_path,
            &options.container_name,
            &build_id,
            &build_prefix,
        )?;
        routes.insert(
            remote_entry_path.clone(),
            FederationRoute {
                bytes: remote_entry_source.into_bytes(),
                mime: "text/javascript".to_owned(),
                source_map_url: Some(format!("{base_path}{remote_entry_map_path}")),
            },
        );
        routes.insert(
            remote_entry_map_path,
            FederationRoute {
                bytes: remote_entry_map.into_bytes(),
                mime: "application/source-map+json".to_owned(),
                source_map_url: None,
            },
        );
        if let Some(bootstrap) = &options.bootstrap {
            let mut bootstrap =
                bootstrap.replace(FEDERATION_BUILD_ID_PLACEHOLDER, build_id.as_str());
            bootstrap.push_str("\nconst __wake_dev_asset_contexts_symbol__=Symbol.for('wake.federation.asset-contexts.v1');\n");
            bootstrap.push_str("let __wake_dev_asset_contexts__=globalThis[__wake_dev_asset_contexts_symbol__];\nif(!(__wake_dev_asset_contexts__ instanceof Map)){__wake_dev_asset_contexts__=new Map();Object.defineProperty(globalThis,__wake_dev_asset_contexts_symbol__,{value:__wake_dev_asset_contexts__,configurable:false})}\n");
            bootstrap.push_str("__wake_dev_asset_contexts__.set(new URL('../../bundle.js',import.meta.url).href,Object.freeze(");
            bootstrap.push_str(
                &serde_json::json!({
                    "name": options.container_name,
                    "buildId": build_id.as_str(),
                    "generation": generation,
                    "fileName": "bundle.js",
                    "kind": "javascript",
                    "developmentLocal": true,
                })
                .to_string(),
            );
            bootstrap.push_str("));\n");
            routes.insert(
                "@wake/federation/bootstrap.mjs".to_owned(),
                FederationRoute {
                    bytes: bootstrap.into_bytes(),
                    mime: "text/javascript".to_owned(),
                    source_map_url: None,
                },
            );
        }
        if let Some(application_loader_export) = &options.application_loader_export {
            let standalone = standalone_source(
                &options.container_name,
                &build_id,
                application_loader_export,
            );
            routes.insert(
                STANDALONE_PATH.to_owned(),
                FederationRoute {
                    bytes: standalone.into_bytes(),
                    mime: "text/javascript".to_owned(),
                    source_map_url: None,
                },
            );
        }

        let output_assets =
            output_asset_lookup(output, &options.container_name, &build_id, &build_prefix)?;
        let mut expose_identities = BTreeMap::new();
        let mut exposes = BTreeMap::new();
        for descriptor in &options.exposes {
            let chunk = find_chunk(output, &descriptor.chunk_name)?;
            let closure = dependency_first_closure(output, chunk)?;
            let mut initial_chunks = closure.clone();
            initial_chunks.push(chunk);
            let initial_files = initial_chunks
                .iter()
                .map(|chunk| chunk.file_name.as_str())
                .collect::<BTreeSet<_>>();
            let all_chunks = transitive_dynamic_chunk_closure(output, &initial_chunks)?;
            let initial_module_ids = initial_chunks
                .iter()
                .flat_map(|chunk| chunk.module_ids.iter().copied())
                .collect::<BTreeSet<_>>();
            let all_module_ids = all_chunks
                .iter()
                .flat_map(|chunk| chunk.module_ids.iter().copied())
                .collect::<BTreeSet<_>>();
            validate_host_rendered_css_policy(descriptor, output, &all_module_ids)?;
            let mut identity = Vec::new();
            append_identity(
                &mut identity,
                "descriptor",
                &serde_json::to_vec(&(
                    descriptor.key.as_str(),
                    descriptor.mode,
                    descriptor.scope.as_str(),
                    descriptor.shadow,
                    descriptor.allow_global_css,
                    descriptor.loader_export.as_str(),
                ))
                .map_err(|error| error.to_string())?,
            );
            let mut identity_styles = BTreeSet::new();
            for reachable in &all_chunks {
                append_identity(
                    &mut identity,
                    &reachable.file_name,
                    reachable.code.as_bytes(),
                );
                identity_styles.extend(reachable.styles.iter().cloned());
            }
            for style in identity_styles {
                let output_asset = output
                    .assets
                    .iter()
                    .find(|asset| asset.file_name == style)
                    .ok_or_else(|| {
                        format!(
                            "federation expose `{}` references missing style `{style}`",
                            descriptor.key
                        )
                    })?;
                append_identity(&mut identity, &style, &output_asset.bytes);
            }
            for output_asset in output.assets.iter().filter(|asset| {
                !asset.is_css
                    && asset
                        .owner_module_ids
                        .iter()
                        .any(|owner| all_module_ids.contains(owner))
            }) {
                append_identity(&mut identity, &output_asset.file_name, &output_asset.bytes);
            }
            expose_identities.insert(descriptor.key.clone(), digest_bytes(&identity).0);

            let entry = output_assets
                .get(&chunk.file_name)
                .cloned()
                .ok_or_else(|| {
                    format!(
                        "missing asset metadata for expose chunk `{}`",
                        chunk.file_name
                    )
                })?;
            let source_map = output_assets
                .get(&format!("{}.map", chunk.file_name))
                .cloned();
            let css = ordered_styles(&closure, chunk)
                .into_iter()
                .filter_map(|style| output_assets.get(style).cloned())
                .collect::<Vec<_>>();
            let mut synchronous_assets = closure
                .iter()
                .filter_map(|dependency| output_assets.get(&dependency.file_name).cloned())
                .collect::<Vec<_>>();
            synchronous_assets.extend(
                output
                    .assets
                    .iter()
                    .filter(|asset| !asset.is_css)
                    .filter(|asset| {
                        asset
                            .owner_module_ids
                            .iter()
                            .any(|owner| initial_module_ids.contains(owner))
                    })
                    .filter_map(|asset| output_assets.get(&asset.file_name).cloned()),
            );
            deduplicate_assets(&mut synchronous_assets);

            let mut asynchronous_assets = Vec::new();
            for reachable in &all_chunks {
                if !initial_files.contains(reachable.file_name.as_str())
                    && let Some(asset) = output_assets.get(&reachable.file_name)
                {
                    asynchronous_assets.push(asset.clone());
                }
                if reachable.file_name != chunk.file_name
                    && let Some(map) = output_assets.get(&format!("{}.map", reachable.file_name))
                {
                    asynchronous_assets.push(map.clone());
                }
                if !initial_files.contains(reachable.file_name.as_str()) {
                    asynchronous_assets.extend(
                        reachable
                            .styles
                            .iter()
                            .filter_map(|style| output_assets.get(style).cloned()),
                    );
                }
            }
            asynchronous_assets.extend(
                output
                    .assets
                    .iter()
                    .filter(|asset| !asset.is_css)
                    .filter(|asset| {
                        !asset
                            .owner_module_ids
                            .iter()
                            .any(|owner| initial_module_ids.contains(owner))
                            && asset
                                .owner_module_ids
                                .iter()
                                .any(|owner| all_module_ids.contains(owner))
                    })
                    .filter_map(|asset| output_assets.get(&asset.file_name).cloned()),
            );
            deduplicate_assets(&mut asynchronous_assets);

            exposes.insert(
                descriptor.key.clone(),
                ExposedModule {
                    mode: descriptor.mode,
                    scope: descriptor.scope.clone(),
                    shadow: descriptor.shadow,
                    entry,
                    css,
                    source_map,
                    synchronous_assets,
                    asynchronous_assets,
                },
            );
        }

        let shared = bind_shared_fallback(options, output, &output_assets)?;
        let shared_identity = digest_bytes(&shared_identity_bytes(options, output)?).0;

        let mut manifest = Manifest::new(
            ContainerName::new(&options.container_name),
            build_id.clone(),
            if options.browser_target.is_empty() {
                "development".to_owned()
            } else {
                options.browser_target.clone()
            },
            remote_entry,
        );
        manifest.remote_entry_source_map = Some(remote_entry_source_map);
        manifest.exposes = exposes;
        manifest.shared = shared;
        manifest.development = Some(DevelopmentMetadata {
            updates_url: updates_url.to_owned(),
            generation,
        });

        if let Some(prepared_types) = prepared_types {
            let types = prepared_types.bind(&build_id)?;
            validate_type_output(&types, &options.container_name, &build_id, &options.exposes)?;
            let path = format!("{build_prefix}/types.json");
            let declaration_path = format!("{build_prefix}/index.d.ts");
            let type_asset = asset(
                AssetKind::Other,
                relative_url(&path),
                &types.bundle_json,
                "application/json",
            );
            manifest.types = Some(TypeArtifact {
                build_id: build_id.clone(),
                url: type_asset.url.clone(),
                content_hash: type_asset.content_hash,
                integrity: type_asset.integrity,
                size: type_asset.size,
                format: TypeArtifactFormat::DeclarationBundle,
            });
            routes.insert(
                path,
                FederationRoute {
                    bytes: types.bundle_json,
                    mime: "application/json".to_owned(),
                    source_map_url: None,
                },
            );
            routes.insert(
                declaration_path,
                FederationRoute {
                    bytes: types.ambient_declaration.into_bytes(),
                    mime: "text/typescript".to_owned(),
                    source_map_url: None,
                },
            );
        }

        manifest.validate().map_err(|error| error.to_string())?;
        let manifest_bytes =
            serde_json::to_vec_pretty(&manifest).map_err(|error| error.to_string())?;
        routes.insert(
            MANIFEST_PATH.to_owned(),
            FederationRoute {
                bytes: manifest_bytes.clone(),
                mime: "application/json".to_owned(),
                source_map_url: None,
            },
        );

        let snapshot = Self {
            manifest,
            routes,
            runtime_identity,
            control_identity,
            types_identity,
            expose_identities,
            shared_identity,
        };
        let update = previous.and_then(|previous| snapshot.update_from(previous));
        if previous.is_some_and(|previous| previous.manifest.build_id == snapshot.manifest.build_id)
        {
            return Ok((previous.expect("checked previous").clone(), None));
        }
        Ok((snapshot, update))
    }

    fn update_from(&self, previous: &Self) -> Option<DevUpdate> {
        if self.manifest.build_id == previous.manifest.build_id {
            return None;
        }
        let keys = previous
            .expose_identities
            .keys()
            .chain(self.expose_identities.keys())
            .cloned()
            .collect::<BTreeSet<_>>();
        let changed_exposes = keys
            .iter()
            .filter(|key| previous.expose_identities.get(*key) != self.expose_identities.get(*key))
            .cloned()
            .collect::<Vec<_>>();
        let only_types_changed = changed_exposes.is_empty()
            && self.runtime_identity == previous.runtime_identity
            && self.shared_identity == previous.shared_identity
            && self.types_identity != previous.types_identity;
        let isolated_only = !changed_exposes.is_empty()
            && self.shared_identity == previous.shared_identity
            && self.control_identity == previous.control_identity
            && changed_exposes.iter().all(|key| {
                previous
                    .manifest
                    .exposes
                    .get(key)
                    .zip(self.manifest.exposes.get(key))
                    .is_some_and(|(old, new)| {
                        old.mode == ExposeMode::Isolated && new.mode == ExposeMode::Isolated
                    })
            });
        let action = if only_types_changed {
            DevUpdateAction::TypesOnly
        } else if isolated_only {
            DevUpdateAction::IsolatedRemount
        } else {
            DevUpdateAction::FullReload
        };
        let mut update = DevUpdate::new(
            self.manifest.name.clone(),
            Some(previous.manifest.build_id.clone()),
            self.manifest.build_id.clone(),
            self.generation(),
            action,
        );
        update.changed_exposes = changed_exposes;
        update.types_hash = self
            .manifest
            .types
            .as_ref()
            .map(|types| types.content_hash.clone());
        Some(update.normalized())
    }
}

fn validate_expose_descriptors(
    options: &FederationBuildOptions,
    output: &BuildOutput,
) -> Result<(), String> {
    let mut keys = BTreeSet::new();
    let mut chunks = BTreeSet::new();
    let mut exports = BTreeSet::new();
    for expose in &options.exposes {
        if !keys.insert(expose.key.clone()) {
            return Err(format!("duplicate development expose `{}`", expose.key));
        }
        if expose.chunk_name.is_empty() || !chunks.insert(expose.chunk_name.clone()) {
            return Err(format!(
                "development expose `{}` has an empty or duplicate chunk name",
                expose.key
            ));
        }
        if expose.loader_export.is_empty() || !exports.insert(expose.loader_export.clone()) {
            return Err(format!(
                "development expose `{}` has an empty or duplicate loader export",
                expose.key
            ));
        }
        find_chunk(output, &expose.chunk_name)?;
    }
    if let Some(shared) = &options.shared_fallback {
        find_chunk(output, &shared.chunk_name)?;
        if shared.loader_export.is_empty() {
            return Err("development shared fallback loader export is empty".to_owned());
        }
    }
    if options
        .application_loader_export
        .as_ref()
        .is_some_and(String::is_empty)
    {
        return Err("development application loader export is empty".to_owned());
    }
    Ok(())
}

fn bind_shared_fallback(
    options: &FederationBuildOptions,
    output: &BuildOutput,
    output_assets: &BTreeMap<String, Asset>,
) -> Result<SharedManifest, String> {
    let mut shared = options.shared_manifest.clone();
    let needs_fallback = shared
        .offers
        .iter()
        .any(|offer| offer.policy.fallback && offer.asset.is_none())
        || shared
            .requirements
            .iter()
            .any(|requirement| requirement.policy.fallback && requirement.fallback.is_none());
    let Some(descriptor) = &options.shared_fallback else {
        if needs_fallback {
            return Err(
                "development shared policy requires a fallback but no retained fallback root was configured"
                    .to_owned(),
            );
        }
        return Ok(shared);
    };
    let chunk = find_chunk(output, &descriptor.chunk_name)?;
    if !chunk.imports.is_empty() || !chunk.dynamic_imports.is_empty() || !chunk.styles.is_empty() {
        return Err(format!(
            "development shared fallback chunk `{}` is not a self-contained JavaScript asset",
            descriptor.chunk_name
        ));
    }
    let fallback_modules = chunk.module_ids.iter().copied().collect::<BTreeSet<_>>();
    if let Some(asset) = output.assets.iter().find(|asset| {
        asset
            .owner_module_ids
            .iter()
            .any(|owner| fallback_modules.contains(owner))
    }) {
        return Err(format!(
            "development shared fallback chunk `{}` owns external asset `{}` and is not a self-contained JavaScript asset",
            descriptor.chunk_name, asset.file_name
        ));
    }
    let fallback = output_assets
        .get(&chunk.file_name)
        .filter(|asset| asset.kind == AssetKind::JavaScript)
        .cloned()
        .ok_or_else(|| {
            format!(
                "missing JavaScript asset metadata for shared fallback chunk `{}`",
                descriptor.chunk_name
            )
        })?;
    for offer in &mut shared.offers {
        if offer.policy.fallback {
            offer.asset = Some(fallback.clone());
        }
    }
    for requirement in &mut shared.requirements {
        if requirement.policy.fallback {
            requirement.fallback = Some(fallback.clone());
        }
    }
    Ok(shared)
}

fn find_chunk<'a>(output: &'a BuildOutput, name: &str) -> Result<&'a OutputChunk, String> {
    let mut matching = output.chunks.iter().filter(|chunk| chunk.name == name);
    let chunk = matching
        .next()
        .ok_or_else(|| format!("retained federation build did not emit chunk `{name}`"))?;
    if matching.next().is_some() {
        return Err(format!(
            "retained federation build emitted duplicate chunk name `{name}`"
        ));
    }
    if chunk.is_entry {
        return Err(format!(
            "federation dynamic root `{name}` resolved to the application entry"
        ));
    }
    Ok(chunk)
}

fn dependency_first_closure<'a>(
    output: &'a BuildOutput,
    root: &'a OutputChunk,
) -> Result<Vec<&'a OutputChunk>, String> {
    let by_file = output
        .chunks
        .iter()
        .map(|chunk| (chunk.file_name.as_str(), chunk))
        .collect::<BTreeMap<_, _>>();
    let mut visiting = BTreeSet::new();
    let mut visited = BTreeSet::new();
    let mut ordered = Vec::new();
    fn visit<'a>(
        chunk: &'a OutputChunk,
        by_file: &BTreeMap<&str, &'a OutputChunk>,
        visiting: &mut BTreeSet<String>,
        visited: &mut BTreeSet<String>,
        ordered: &mut Vec<&'a OutputChunk>,
    ) -> Result<(), String> {
        if visited.contains(&chunk.file_name) {
            return Ok(());
        }
        if !visiting.insert(chunk.file_name.clone()) {
            return Err(format!(
                "federation chunk dependency cycle at `{}`",
                chunk.file_name
            ));
        }
        for dependency in &chunk.imports {
            let dependency_chunk = by_file.get(dependency.as_str()).ok_or_else(|| {
                format!(
                    "federation chunk `{}` imports missing chunk `{dependency}`",
                    chunk.file_name
                )
            })?;
            visit(dependency_chunk, by_file, visiting, visited, ordered)?;
        }
        visiting.remove(&chunk.file_name);
        visited.insert(chunk.file_name.clone());
        ordered.push(chunk);
        Ok(())
    }
    for dependency in &root.imports {
        let chunk = by_file.get(dependency.as_str()).ok_or_else(|| {
            format!(
                "federation expose chunk `{}` imports missing chunk `{dependency}`",
                root.file_name
            )
        })?;
        visit(chunk, &by_file, &mut visiting, &mut visited, &mut ordered)?;
    }
    Ok(ordered)
}

fn transitive_dynamic_chunk_closure<'a>(
    output: &'a BuildOutput,
    initial: &[&'a OutputChunk],
) -> Result<Vec<&'a OutputChunk>, String> {
    let by_file = output
        .chunks
        .iter()
        .map(|chunk| (chunk.file_name.as_str(), chunk))
        .collect::<BTreeMap<_, _>>();
    let mut ordered = initial.to_vec();
    let mut visited = initial
        .iter()
        .map(|chunk| chunk.file_name.clone())
        .collect::<BTreeSet<_>>();
    let mut scan = 0;
    while scan < ordered.len() {
        let chunk = ordered[scan];
        for target in &chunk.dynamic_imports {
            let target = by_file.get(target.as_str()).copied().ok_or_else(|| {
                format!(
                    "federation chunk `{}` dynamically imports missing chunk `{target}`",
                    chunk.file_name
                )
            })?;
            for dependency in dependency_first_closure(output, target)? {
                if visited.insert(dependency.file_name.clone()) {
                    ordered.push(dependency);
                }
            }
            if visited.insert(target.file_name.clone()) {
                ordered.push(target);
            }
        }
        scan += 1;
    }
    Ok(ordered)
}

fn ordered_styles<'a>(dependencies: &[&'a OutputChunk], root: &'a OutputChunk) -> Vec<&'a str> {
    let mut seen = BTreeSet::new();
    let mut ordered = Vec::new();
    for style in dependencies
        .iter()
        .flat_map(|chunk| chunk.styles.iter())
        .chain(root.styles.iter())
    {
        if seen.insert(style.as_str()) {
            ordered.push(style.as_str());
        }
    }
    ordered
}

fn validate_host_rendered_css_policy(
    expose: &FederationExposeBuild,
    output: &BuildOutput,
    reachable_module_ids: &BTreeSet<u32>,
) -> Result<(), String> {
    if expose.mode != ExposeMode::HostRendered || expose.allow_global_css {
        return Ok(());
    }
    let unscoped = output
        .assets
        .iter()
        .filter(|asset| asset.is_css)
        .filter(|asset| {
            asset
                .unscoped_css_owner_module_ids
                .iter()
                .any(|owner| reachable_module_ids.contains(owner))
        })
        .map(|asset| asset.file_name.as_str())
        .collect::<Vec<_>>();
    if unscoped.is_empty() {
        return Ok(());
    }
    Err(format!(
        "[{}] host-rendered expose `{}` reaches unscoped CSS {}; use CSS Modules or Wake CSS-in-JS, or explicitly set allow_global_css=true",
        FederationErrorCode::ConfigInvalid.as_str(),
        expose.key,
        unscoped
            .iter()
            .map(|file| format!("`{file}`"))
            .collect::<Vec<_>>()
            .join(", ")
    ))
}

fn output_routes(
    output: &BuildOutput,
    base_path: &str,
    container: &str,
    build_id: &BuildId,
    build_prefix: &str,
) -> Result<BTreeMap<String, FederationRoute>, String> {
    let mut routes = BTreeMap::new();
    routes.insert(
        "bundle.js".to_owned(),
        FederationRoute {
            bytes: output.bundle.as_bytes().to_vec(),
            mime: "text/javascript".to_owned(),
            source_map_url: output.chunks[output.entry_chunk]
                .source_map
                .as_ref()
                .map(|_| format!("{base_path}bundle.js.map")),
        },
    );
    routes.insert(
        format!("{build_prefix}/{CONTAINER_ENTRY_FILE}"),
        FederationRoute {
            bytes: output.bundle.as_bytes().to_vec(),
            mime: "text/javascript".to_owned(),
            source_map_url: output.chunks[output.entry_chunk]
                .source_map
                .as_ref()
                .map(|_| format!("{base_path}{build_prefix}/{CONTAINER_ENTRY_FILE}.map")),
        },
    );
    for (index, chunk) in output.chunks.iter().enumerate() {
        if index != output.entry_chunk {
            routes.insert(
                format!("{build_prefix}/{}", chunk.file_name),
                FederationRoute {
                    bytes: chunk.code.as_bytes().to_vec(),
                    mime: "text/javascript".to_owned(),
                    source_map_url: chunk
                        .source_map
                        .as_ref()
                        .map(|_| format!("{base_path}{build_prefix}/{}.map", chunk.file_name)),
                },
            );
        }
        if let Some(map) = &chunk.source_map {
            let rewritten = rewrite_source_map(map, container, build_id, &chunk.file_name)?;
            let path = if index == output.entry_chunk {
                "bundle.js.map".to_owned()
            } else {
                format!("{build_prefix}/{}.map", chunk.file_name)
            };
            routes.insert(
                path,
                FederationRoute {
                    bytes: rewritten.into_bytes(),
                    mime: "application/source-map+json".to_owned(),
                    source_map_url: None,
                },
            );
            if index == output.entry_chunk {
                routes.insert(
                    format!("{build_prefix}/{CONTAINER_ENTRY_FILE}.map"),
                    FederationRoute {
                        bytes: rewrite_source_map(map, container, build_id, CONTAINER_ENTRY_FILE)?
                            .into_bytes(),
                        mime: "application/source-map+json".to_owned(),
                        source_map_url: None,
                    },
                );
            }
        }
    }
    for output_asset in &output.assets {
        routes.insert(
            format!("{build_prefix}/{}", output_asset.file_name),
            FederationRoute {
                bytes: output_asset.bytes.clone(),
                mime: if output_asset.is_css {
                    "text/css".to_owned()
                } else {
                    super::mime_for(&output_asset.file_name)
                        .split(';')
                        .next()
                        .unwrap_or("application/octet-stream")
                        .to_owned()
                },
                source_map_url: None,
            },
        );
    }
    Ok(routes)
}

fn output_asset_lookup(
    output: &BuildOutput,
    container: &str,
    build_id: &BuildId,
    build_prefix: &str,
) -> Result<BTreeMap<String, Asset>, String> {
    let mut assets = BTreeMap::new();
    assets.insert(
        CONTAINER_ENTRY_FILE.to_owned(),
        asset(
            AssetKind::JavaScript,
            relative_url(&format!("{build_prefix}/{CONTAINER_ENTRY_FILE}")),
            output.bundle.as_bytes(),
            "text/javascript",
        ),
    );
    for (index, chunk) in output.chunks.iter().enumerate() {
        if index != output.entry_chunk {
            assets.insert(
                chunk.file_name.clone(),
                asset(
                    AssetKind::JavaScript,
                    relative_url(&format!("{build_prefix}/{}", chunk.file_name)),
                    chunk.code.as_bytes(),
                    "text/javascript",
                ),
            );
        }
        if let Some(map) = &chunk.source_map {
            let rewritten = rewrite_source_map(map, container, build_id, &chunk.file_name)?;
            let path = if index == output.entry_chunk {
                format!("{CONTAINER_ENTRY_FILE}.map")
            } else {
                format!("{}.map", chunk.file_name)
            };
            assets.insert(
                path.clone(),
                asset(
                    AssetKind::SourceMap,
                    relative_url(&format!("{build_prefix}/{path}")),
                    rewritten.as_bytes(),
                    "application/source-map+json",
                ),
            );
        }
    }
    for output_asset in &output.assets {
        let kind = if output_asset.is_css {
            AssetKind::Css
        } else {
            AssetKind::Other
        };
        let mime = if output_asset.is_css {
            "text/css"
        } else {
            super::mime_for(&output_asset.file_name)
                .split(';')
                .next()
                .unwrap_or("application/octet-stream")
        };
        assets.insert(
            output_asset.file_name.clone(),
            asset(
                kind,
                relative_url(&format!("{build_prefix}/{}", output_asset.file_name)),
                &output_asset.bytes,
                mime,
            ),
        );
    }
    Ok(assets)
}

fn runtime_identity_bytes(
    options: &FederationBuildOptions,
    output: &BuildOutput,
) -> Result<Vec<u8>, String> {
    let mut identity = Vec::new();
    append_identity(
        &mut identity,
        "federation-metadata",
        &serde_json::to_vec(&(
            options.container_name.as_str(),
            options.browser_target.as_str(),
            &options.exposes,
            &options.shared_manifest,
            &options.shared_fallback,
            options.application_loader_export.as_deref(),
            options.remote_entry_template.as_deref(),
        ))
        .map_err(|error| error.to_string())?,
    );
    for chunk in &output.chunks {
        append_identity(&mut identity, &chunk.file_name, chunk.code.as_bytes());
    }
    for asset in &output.assets {
        append_identity(&mut identity, &asset.file_name, &asset.bytes);
        let owner_chunks = output
            .chunks
            .iter()
            .filter(|chunk| {
                chunk
                    .module_ids
                    .iter()
                    .any(|module_id| asset.owner_module_ids.contains(module_id))
            })
            .map(|chunk| chunk.file_name.as_str())
            .collect::<BTreeSet<_>>();
        let owners = serde_json::to_vec(&owner_chunks).map_err(|error| error.to_string())?;
        append_identity(
            &mut identity,
            &format!("{}.owners", asset.file_name),
            &owners,
        );
        let unscoped_owner_chunks = output
            .chunks
            .iter()
            .filter(|chunk| {
                chunk
                    .module_ids
                    .iter()
                    .any(|module_id| asset.unscoped_css_owner_module_ids.contains(module_id))
            })
            .map(|chunk| chunk.file_name.as_str())
            .collect::<BTreeSet<_>>();
        let unscoped_owners =
            serde_json::to_vec(&unscoped_owner_chunks).map_err(|error| error.to_string())?;
        append_identity(
            &mut identity,
            &format!("{}.unscoped-css-owners", asset.file_name),
            &unscoped_owners,
        );
    }
    Ok(identity)
}

fn shared_identity_bytes(
    options: &FederationBuildOptions,
    output: &BuildOutput,
) -> Result<Vec<u8>, String> {
    let mut identity =
        serde_json::to_vec(&(&options.shared_manifest, options.shared_fallback.as_ref()))
            .map_err(|error| error.to_string())?;
    if let Some(descriptor) = &options.shared_fallback {
        let chunk = find_chunk(output, &descriptor.chunk_name)?;
        append_identity(&mut identity, &chunk.file_name, chunk.code.as_bytes());
    }
    Ok(identity)
}

fn append_identity(destination: &mut Vec<u8>, name: &str, bytes: &[u8]) {
    destination.extend_from_slice(&(name.len() as u64).to_be_bytes());
    destination.extend_from_slice(name.as_bytes());
    destination.extend_from_slice(&(bytes.len() as u64).to_be_bytes());
    destination.extend_from_slice(bytes);
}

fn content_build_id(runtime: &[u8], types: Option<&[u8]>) -> BuildId {
    let mut framed = Vec::new();
    append_identity(&mut framed, "runtime", runtime);
    if let Some(types) = types {
        append_identity(&mut framed, "types", types);
    }
    let hash = digest_bytes(&framed).0;
    BuildId::new(format!("sha384-{}", &hash[..32]))
}

fn validate_type_output(
    output: &FederationTypeOutput,
    container: &str,
    build_id: &BuildId,
    exposes: &[FederationExposeBuild],
) -> Result<(), String> {
    let value: serde_json::Value = serde_json::from_slice(&output.bundle_json)
        .map_err(|error| format!("invalid federation declaration JSON: {error}"))?;
    if value.get("name").and_then(serde_json::Value::as_str) != Some(container)
        || value.get("buildId").and_then(serde_json::Value::as_str) != Some(build_id.as_str())
    {
        return Err(
            "federation declaration identity does not match its JavaScript build".to_owned(),
        );
    }
    let expected = exposes
        .iter()
        .map(|expose| expose.key.as_str())
        .collect::<BTreeSet<_>>();
    let observed = value
        .get("exposes")
        .and_then(serde_json::Value::as_object)
        .ok_or_else(|| "federation declaration bundle has no exposes object".to_owned())?
        .keys()
        .map(String::as_str)
        .collect::<BTreeSet<_>>();
    if expected != observed {
        return Err("federation declarations do not exactly cover manifest exposes".to_owned());
    }
    if output.ambient_declaration.is_empty() {
        return Err("federation ambient declaration is empty".to_owned());
    }
    Ok(())
}

fn asset(kind: AssetKind, url: String, bytes: &[u8], mime: &str) -> Asset {
    let (content_hash, integrity) = digest_bytes(bytes);
    Asset::new(kind, url, content_hash, integrity, mime, bytes.len() as u64)
}

fn digest_bytes(bytes: &[u8]) -> (String, String) {
    let digest = digest(&SHA384, bytes);
    let raw = digest.as_ref();
    let mut hex = String::with_capacity(raw.len() * 2);
    const DIGITS: &[u8; 16] = b"0123456789abcdef";
    for byte in raw {
        hex.push(char::from(DIGITS[usize::from(byte >> 4)]));
        hex.push(char::from(DIGITS[usize::from(byte & 0x0f)]));
    }
    (hex, format!("sha384-{}", BASE64.encode(raw)))
}

fn relative_url(path: &str) -> String {
    format!("./{path}")
}

fn deduplicate_assets(assets: &mut Vec<Asset>) {
    let mut seen = BTreeSet::new();
    assets.retain(|asset| seen.insert((asset.kind, asset.url.clone())));
}

fn rewrite_source_map(
    source_map: &str,
    container: &str,
    build_id: &BuildId,
    file_name: &str,
) -> Result<String, String> {
    let mut value: serde_json::Value = serde_json::from_str(source_map)
        .map_err(|error| format!("invalid federation source map: {error}"))?;
    let object = value
        .as_object_mut()
        .ok_or_else(|| "federation source map root is not an object".to_owned())?;
    object.insert(
        "file".to_owned(),
        serde_json::Value::String(file_name.to_owned()),
    );
    object.insert(
        "sourceRoot".to_owned(),
        serde_json::Value::String(format!("wake://{container}@{build_id}/")),
    );
    if let Some(sources) = object
        .get_mut("sources")
        .and_then(serde_json::Value::as_array_mut)
    {
        for source in sources {
            if let Some(value) = source.as_str() {
                let normalized = value.replace('\\', "/");
                let normalized = normalized
                    .trim_start_matches("../")
                    .trim_start_matches("./");
                *source = serde_json::Value::String(normalized.to_owned());
            }
        }
    }
    serde_json::to_string(&value).map_err(|error| error.to_string())
}

fn generated_source_map(source: &str, source_name: &str, file: &str) -> Result<String, String> {
    let lines = source.lines().count().max(1);
    let mut mappings = String::new();
    for line in 0..lines {
        if line != 0 {
            mappings.push(';');
        }
        mappings.push_str(if line == 0 { "AAAA" } else { "AACA" });
    }
    serde_json::to_string(&serde_json::json!({
        "version": 3,
        "file": file,
        "sourceRoot": "",
        "sources": [source_name],
        "sourcesContent": [source],
        "names": [],
        "mappings": mappings,
    }))
    .map_err(|error| error.to_string())
}

fn combined_remote_entry_map(
    output: &BuildOutput,
    abi_source: &str,
    container: &str,
    build_id: &BuildId,
    file: &str,
) -> Result<String, String> {
    let abi_map = serde_json::from_str::<serde_json::Value>(&generated_source_map(
        abi_source,
        &format!("wake://{container}@{build_id}/remoteEntry-runtime.mjs"),
        file,
    )?)
    .map_err(|error| error.to_string())?;
    let Some(entry_map) = output.entry().source_map.as_deref() else {
        return generated_source_map(
            &format!("{}\n{abi_source}", output.bundle),
            &format!("wake://{container}@{build_id}/remoteEntry.mjs"),
            file,
        );
    };
    let entry_map = rewrite_source_map(entry_map, container, build_id, file)?;
    let entry_map =
        serde_json::from_str::<serde_json::Value>(&entry_map).map_err(|error| error.to_string())?;
    serde_json::to_string(&serde_json::json!({
        "version": 3,
        "file": file,
        "sections": [
            {"offset": {"line": 0, "column": 0}, "map": entry_map},
            {
                "offset": {
                    "line": output.bundle.bytes().filter(|byte| *byte == b'\n').count() + 1,
                    "column": 0
                },
                "map": abi_map,
            },
        ],
    }))
    .map_err(|error| error.to_string())
}

