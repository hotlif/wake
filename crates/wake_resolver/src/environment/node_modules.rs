//! Read-only installation queries for consumers with a native node_modules resolver.
use super::{PnpRegistry, PnpRoute, ResolutionContext};
use crate::{PnpLoadError, PnpManifest};
use std::collections::BTreeSet;
use std::path::{Path, PathBuf};
use std::sync::Arc;
use wake_common::fs::normalize;

/// Lookup output, not a second resolver: exports/main/conditions remain the consumer's policy.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum NodeModulesPath {
    /// Unprojected file or directory. Read through the environment's PnP-aware filesystem.
    Native(PathBuf),
    /// A dependency location selected by PnP; retain its authority for subsequent queries.
    Projected {
        path: PathBuf,
        context: ResolutionContext,
    },
    /// Synthetic node_modules or scope directory, containing sorted visible child names.
    Directory(Vec<String>),
    /// PnP rejection is final, including an unmet peer. Do not consult a physical shadow tree.
    Missing,
}

#[derive(Clone)]
pub struct NodeModulesView {
    registry: Arc<PnpRegistry>,
    context: ResolutionContext,
}
impl NodeModulesView {
    pub(super) fn new(registry: Arc<PnpRegistry>, context: ResolutionContext) -> Self {
        Self { registry, context }
    }

    /// Resolve the issuer's authority, retaining this view's context only where it owns the path.
    pub fn context_for_issuer(&self, issuer: &Path) -> Result<ResolutionContext, PnpLoadError> {
        self.registry
            .context_for_issuer_with(&normalize(issuer), &self.context)
    }

    /// Reuse the registry with a previously selected opaque authority.
    /// An actual nested project root still takes precedence on every query.
    pub fn in_context(&self, context: ResolutionContext) -> Self {
        Self::new(self.registry.clone(), context)
    }

    /// Project an installation query while keeping ordinary/ignored issuers on classic paths.
    /// Each synthetic node_modules boundary uses its own actual issuer and retained PnP authority.
    pub fn resolve(&self, path: &Path) -> Result<NodeModulesPath, PnpLoadError> {
        let path = normalize(path);
        // The query may be a package directory itself. Its parent belongs to a different
        // package and would reinterpret an installed archive's node_modules as a lookup.
        let issuer = path.as_path();
        let owner = match self.registry.route_with(issuer, &self.context)? {
            PnpRoute::Managed(owner) => owner,
            PnpRoute::NoManifest => {
                if let Some(root) = &self.context.pnp_root {
                    let manifest = self.registry.manifest(root)?;
                    for directory in path.ancestors() {
                        let Some(name) = directory.file_name() else {
                            continue;
                        };
                        #[cfg(windows)]
                        let boundary = name.eq_ignore_ascii_case("node_modules");
                        #[cfg(not(windows))]
                        let boundary = name == "node_modules";
                        if boundary
                            && directory
                                .parent()
                                .is_some_and(|parent| manifest.has_package_below(parent))
                        {
                            return Ok(NodeModulesPath::Missing);
                        }
                    }
                }
                return Ok(NodeModulesPath::Native(path));
            }
            PnpRoute::Classic => return Ok(NodeModulesPath::Native(path)),
        };
        // Existing installed package locations already contain archive/node_modules segments.
        // Those are physical payload paths; only boundaries below the owner are synthetic.
        let location = owner
            .issuer_location(issuer)
            .expect("managed issuer has a package");
        let Ok(relative) = path.strip_prefix(location) else {
            return Ok(NodeModulesPath::Native(path));
        };
        let components: Vec<_> = relative
            .components()
            .map(|component| component.as_os_str())
            .collect();
        let mut actual = location.to_owned();
        let mut inherited = ResolutionContext {
            pnp_root: Some(owner.root().to_owned()),
        };
        let mut projected = false;
        let mut index = 0;
        while index < components.len() {
            #[cfg(windows)]
            let boundary = components[index].eq_ignore_ascii_case("node_modules");
            #[cfg(not(windows))]
            let boundary = components[index] == "node_modules";
            if !boundary {
                actual.push(components[index]);
                index += 1;
                continue;
            }
            let PnpRoute::Managed(manifest) = self.registry.route_with(&actual, &inherited)? else {
                actual.push(components[index]);
                index += 1;
                continue;
            };
            index += 1;
            if index == components.len() {
                return Ok(directory(&manifest, &actual, None));
            }
            let Some(first) = components[index].to_str() else {
                return Ok(NodeModulesPath::Missing);
            };
            index += 1;
            let package = if first.starts_with('@') {
                if index == components.len() {
                    return Ok(directory(&manifest, &actual, Some(first)));
                }
                let Some(second) = components[index].to_str() else {
                    return Ok(NodeModulesPath::Missing);
                };
                index += 1;
                format!("{first}/{second}")
            } else {
                first.to_owned()
            };
            if !crate::is_valid_bare_package_specifier(&package) {
                return Ok(NodeModulesPath::Missing);
            }
            let Ok(target) = manifest.resolve_bare(&package, &actual) else {
                return Ok(NodeModulesPath::Missing);
            };
            inherited = ResolutionContext {
                pnp_root: Some(manifest.root().to_owned()),
            };
            inherited = self.registry.context_for_issuer_with(&target, &inherited)?;
            actual = target;
            projected = true;
        }
        Ok(if projected {
            NodeModulesPath::Projected {
                path: actual,
                context: inherited,
            }
        } else {
            NodeModulesPath::Native(actual)
        })
    }
}

fn directory(manifest: &PnpManifest, issuer: &Path, scope: Option<&str>) -> NodeModulesPath {
    let names: BTreeSet<String> = manifest
        .visible_dependencies(issuer)
        .into_iter()
        .filter_map(|name| match scope {
            Some(scope) => name.strip_prefix(&format!("{scope}/")).map(str::to_owned),
            None => Some(
                name.split_once('/')
                    .map_or(name.as_str(), |(scope, _)| scope)
                    .to_owned(),
            ),
        })
        .collect();
    if names.is_empty() && scope.is_some() {
        NodeModulesPath::Missing
    } else {
        NodeModulesPath::Directory(names.into_iter().collect())
    }
}
